//! Оболочка ПК-приложения Axo-Team.
//!
//! Вся логика (аккаунты, каталог, комментарии, баг-репорты, админка) живёт в общем
//! интерфейсе `packages/ui` и работает с Supabase так же, как сайт. Здесь только окно
//! и одно разрешение: открывать внешние ссылки в браузере пользователя.

/// Запускает приложение. Завершается вместе с окном.
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .run(tauri::generate_context!())
        .expect("не удалось запустить приложение Axo-Team");
}
